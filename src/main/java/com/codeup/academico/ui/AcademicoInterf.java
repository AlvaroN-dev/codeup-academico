    // funcion para validar que el nombre no contenga numero
    private static boolean nameValidate(String name) throws Exception{
       for(char c : name.toCharArray()){ 
           if(Character.isDigit(c)){
                throw new Exception("el nombre no es valido");
           }
       }
       return true;
    }
    
    
    private static boolean emailValidate(String email) throws Exception{
        String regex = "^(.+)@(\\S+)$";
        
        boolean validate = email.matches(regex);
        
        if(!validate){
            throw new Exception("El email es invalido");
        }
        
        return true;
    }
      
    
    


