    private void saveDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveDataActionPerformed
        // TODO add your handling code here:
        
        try{
            Academico academic = new Academico();
            
           
            String nameStudent = insertName.getText().trim();
       
            String emailStudent = insertEmail.getText().trim();
             
        
            String courseStudent = insertCourse.getText().trim();
               
            String idStudents = insertid.getText().trim();
        
            
            if(nameStudent.isEmpty() || emailStudent.isEmpty() || courseStudent.isEmpty() || idStudents.isEmpty()){
                throw new Exception("los campos debe de ser ingreados");
            };
            
            nameValidate(nameStudent);
            emailValidate(emailStudent);
            
            
                
            int idStudent;
           
            idStudent = Integer.parseInt(idStudents);
       
        
            academic.setName(nameStudent);
            academic.setEmail(emailStudent);
            academic.setCouser(courseStudent);
            academic.setIdStudent(idStudent);
        
       
            listAcademic.add(academic);
            
            Object[] fila = {academic.getIdStudent() ,academic.getName(),  academic.getCourse() ,academic.getEmail(), };
            
            
            DefaultTableModel model = (DefaultTableModel) tableData.getModel();
            model.addRow(fila);
            
            
           
            insertName.setText("");
            insertEmail.setText("");
            insertCourse.setText("");
            insertid.setText(""); 
        
            
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "la id debe de ser un numero valido");
        }catch(Exception e){
            
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
  
    }//GEN-LAST:event_saveDataActionPerformed

